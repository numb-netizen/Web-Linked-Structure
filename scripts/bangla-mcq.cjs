// Rebuild the local, offline-safe bank, printable sheet and CSV from one source.
//   node scripts/bangla-mcq.cjs [--check]
const fs = require('node:fs');
const path = require('node:path');
const core = require('../site/assets/mcq-core.js');
const ROOT = path.resolve(__dirname, '..');
const bank = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/bangla-mcq.json'), 'utf8'));
const escape = s => String(s).replace(/[&<>"']/g, c => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[c]));
const bn = n => n.toLocaleString('bn-BD');
