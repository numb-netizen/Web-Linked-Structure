function outputs(data) {
  core.validateBank(data);
  const json = JSON.stringify(data).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  return new Map([
    ['site/assets/bangla-mcq-bank.js', `// Generated by scripts/bangla-mcq.cjs. Edit data/bangla-mcq.json instead.\n(function(root){'use strict';const bank=${json};if(typeof module==='object'&&module.exports)module.exports=bank;else root.HSC_BANGLA_MCQ_BANK=bank;})(typeof globalThis!=='undefined'?globalThis:this);\n`],
    ['site/assets/bangla-mcq-sheet.html', renderSheet(data)],
    ['docs/bangla-mcq-sheet.csv', core.csv(core.sheetRows(data))],
  ]);
}
function generate(check = false) {
  const stale = [];
  for (const [name, content] of outputs(bank)) {
    const file = path.join(ROOT, name);
    if (fs.existsSync(file) && fs.readFileSync(file,'utf8') === content) continue;
    stale.push(name);
    if (!check) fs.writeFileSync(file, content);
  }
  return stale;
}
if (require.main === module) {
  const check = process.argv.includes('--check'), stale = generate(check);
  if (check && stale.length) {console.error('MCQ exports out of date: ' + stale.join(', '));process.exitCode=1;}
  else console.log(check ? 'MCQ bank and sheets are up to date' : `MCQ exports updated: ${stale.length}; ${bank.questions.length} questions`);
}
module.exports = {renderSheet, outputs, generate};
